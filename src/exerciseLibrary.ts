type GroupInput = {
  prefix: string;
  category: ExerciseCategory;
  tracking: TrackingMode;
  group: string;
  equipment: string;
  muscles: string[];
  names: string[];
  popular?: string[];
};

function group(input: GroupInput): Exercise[] {
  return input.names.map((raw, index) => {
    const [name, aliasText = ""] = raw.split("|");
    return {
      id: `${input.prefix}-${String(index + 1).padStart(2, "0")}`,
      name,
      aliases: aliasText ? aliasText.split("/") : [],
      category: input.category,
      group: input.group,
      equipment: input.equipment,
      muscles: input.muscles,
      tracking: input.tracking,
      popular: input.popular?.includes(name),
    };
  });
}

