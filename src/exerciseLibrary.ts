export const EQUIPMENT_OPTIONS = Array.from(
  new Set(EXERCISES.map((exercise) => exercise.equipment)),
).sort((a, b) => a.localeCompare(b, "zh-CN"));

export function searchExercises(
  query: string,
  category: ExerciseCategory | "all",
  equipment: string | "all",
): Exercise[] {
  const normalized = query.trim().toLowerCase();
  return EXERCISES.filter((exercise) => {
    if (category !== "all" && exercise.category !== category) return false;
    if (equipment !== "all" && exercise.equipment !== equipment) return false;
    if (!normalized) return true;
    return [
      exercise.name,
      exercise.group,
      exercise.equipment,
      ...exercise.aliases,
      ...exercise.muscles,
      CATEGORY_META[exercise.category].label,
    ]
      .join(" ")
      .toLowerCase()
      .includes(normalized);
  });
}

export function getExercise(id: string): Exercise | undefined {
  return EXERCISES.find((exercise) => exercise.id === id);
}

