export type ExerciseCategory =
  | "strength"
  | "running"
  | "cardio"
  | "swimming"
  | "outdoor"
  | "mobility"
  | "mindbody"
  | "sports";

export type TrackingMode = "sets" | "distance" | "duration" | "swim";

export interface Exercise {
  id: string;
  name: string;
  aliases: string[];
  category: ExerciseCategory;
  group: string;
  equipment: string;
  muscles: string[];
  tracking: TrackingMode;
  popular?: boolean;
}

