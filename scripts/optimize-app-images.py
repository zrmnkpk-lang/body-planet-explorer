"""Generate display-sized WebP artwork from the original, versioned sources.

Run manually with Pillow: python scripts/optimize-app-images.py
Original PNGs remain recoverable from SOURCE_REF; they are not shipped to users.
"""
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import json
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE_REF = "9d06632dacc384b30da3eb6307434d3ad4499bab"
SOURCES = {
    "alex-account": ("companions/alex-account.png", [96, 192], 80),
    "maya-sport": ("companions/maya-sport.png", [320, 480], 77),
    "maya-body-analysis": ("companions/maya-body-analysis.png", [192, 288], 80),
    "landscape": ("visual-v2/alpine-night.png", [960, 1440], 70),
    "metric-atlas": ("visual-v2/body-metric-atlas.png", [256], 82),
    "exercise-atlas": ("visual-v2/maya-exercise-atlas.png", [576, 1080], 78),
}
output = ROOT / "public/assets/app"
output.mkdir(parents=True, exist_ok=True)
manifest, report = {}, []
for name, (relative, widths, quality) in SOURCES.items():
    original = subprocess.check_output(
        ["git", "show", f"{SOURCE_REF}:public/assets/{relative}"], cwd=ROOT
    )
    with Image.open(BytesIO(original)) as source:
        source.load()
        variants = []
        for width in widths:
            height = round(source.height * width / source.width)
            image = source.resize((width, height), Image.Resampling.LANCZOS)
            encoded = BytesIO()
            image.save(encoded, "WEBP", quality=quality, method=6, exact=True)
            data = encoded.getvalue()
            filename = f"{name}-{width}-{sha256(data).hexdigest()[:10]}.webp"
            (output / filename).write_bytes(data)
            variants.append({"src": f"/assets/app/{filename}", "width": width,
                             "height": height, "bytes": len(data)})
        manifest[name] = variants
        report.append({"name": name, "original": f"public/assets/{relative}",
                       "originalBytes": len(original), "variants": variants})

(ROOT / "src/image-assets.json").write_text(json.dumps(manifest, indent=2) + "\n")
def url(name, index=0):
    return f'url("{manifest[name][index]["src"]}")'

(ROOT / "src/image-assets.css").write_text(
    "/* Generated by scripts/optimize-app-images.py. */\n:root {\n"
    f"  --landscape: {url('landscape')};\n"
    f"  --metric-art: {url('metric-atlas')};\n"
    f"  --exercise-art: {url('exercise-atlas')};\n"
    f"  --exercise-art-large: {url('exercise-atlas', 1)};\n"
    "}\n@media (min-width: 600px) {\n"
    f"  :root {{ --landscape: {url('landscape', 1)}; }}\n}}\n"
)
before = sum(item["originalBytes"] for item in report)
after = sum(v["bytes"] for item in report for v in item["variants"])
summary = {"sourceCommit": SOURCE_REF, "originalBytes": before,
           "allVariantsBytes": after, "reductionPercent": round(100 * (1 - after / before), 1),
           "assets": report}
(ROOT / "docs/development/image-budget.json").write_text(json.dumps(summary, indent=2) + "\n")
print(f"Originals: {before:,} bytes; all WebP variants: {after:,} bytes; reduction: {summary['reductionPercent']}%")
for name, variants in manifest.items():
    print(name, ", ".join(f"{v['width']}px: {v['bytes']:,} bytes" for v in variants))
